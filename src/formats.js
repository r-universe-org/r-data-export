import createError from 'http-errors';

// Supported output formats and how they are served
export const formats = {
  'csv': { type: 'text/csv', filename: '.csv' },
  'csv.gz': { type: 'application/gzip', filename: '.csv.gz' },
  'xlsx': { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', filename: '.xlsx' },
  'json': { type: 'application/json' },
  'ndjson': { type: 'text/plain' },
  'rds': { type: 'application/octet-stream', filename: '.rds' },
  'rda': { type: 'application/octet-stream', filename: '.RData' }
};

// Files to extract from the installed (binary) package for this dataset. Without
// lazydata we need the original data file, but we can't run R scripts.
export function dataFiles(pkg, dataset, lazydata, file) {
  if (lazydata) {
    return ['Rdata.rdb', 'Rdata.rdx'];
  }
  if (file && !/\.R$/i.test(file)) {
    return [file];
  }
  const reason = file ? `it is generated by the R script ${file}` : 'no data file was found';
  throw createError(422, `Dataset ${pkg}::${dataset} cannot be exported because ${reason}`);
}
